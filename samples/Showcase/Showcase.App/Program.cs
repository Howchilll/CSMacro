using Showcase.App;

var hero = Cheats.Hero;

// "UI binding": subscribe to change notifications. No notification when the value doesn't change (healing at full HP, setting the level to the cap again).
hero.PropertyChanged += (_, e) =>
    Console.WriteLine($"  [UI] {e.PropertyName} -> {typeof(Hero).GetProperty(e.PropertyName!)!.GetValue(hero)}");

Console.WriteLine("== Debug console: commands registered by [@Command] at startup ==");
foreach (var line in new[]
{
    "help",
    "rename Aria",
    "heal 50",        // already at full HP: clamped to 100, unchanged, no notification
    "hurt 130",       // clamped to 0
    "heal 40",
    "gold 250",
    "class mage",     // enum parsing, case-insensitive
    "level 150",      // clamped to 99
    "level",          // optional argument defaults to 99: unchanged, no notification
    "heal lots",      // argument parsing fails → usage hint
    "fly",            // unknown command
    "status",         // the return value is printed
})
{
    DebugConsole.Execute(line);
}

Console.WriteLine();
Console.WriteLine("== Save / load: code generated by [@Persist] + @WRITE_PERSISTED / @READ_PERSISTED ==");
hero.Combo = 7; // not saved
var stream = new MemoryStream();
hero.Save(new BinaryWriter(stream));
Console.WriteLine($"saved {stream.Length} bytes: {hero}");

var loaded = new Hero();
stream.Position = 0;
loaded.Load(new BinaryReader(stream));
Console.WriteLine($"loaded:         {loaded}");

// Save format fingerprint: after saved fields change, reading an old save fails clearly instead of reading misaligned data
var corrupted = stream.ToArray();
corrupted[0] ^= 0xFF;
try
{
    new Hero().Load(new BinaryReader(new MemoryStream(corrupted)));
}
catch (InvalidDataException e)
{
    Console.WriteLine($"old/foreign save rejected: {e.Message}");
}
