using System.Collections.Generic;
using HowMacro;
using Microsoft.CodeAnalysis;

namespace HowMacro.Engine
{
    public sealed class SourceFile
    {
        public SourceFile(string id, string path, string text)
        {
            Id = id;
            Path = path;
            Text = text;
        }

        /// <summary>The identifier the host uses for the file (the Compile item's Identity in MSBuild).</summary>
        public string Id { get; }

        /// <summary>Absolute path of the original file; written into <c>#line</c> so errors and breakpoints point back here.</summary>
        public string Path { get; }

        public string Text { get; }
    }

    public sealed class ExpandedFile
    {
        public ExpandedFile(string id, string path, string text)
        {
            Id = id;
            Path = path;
            Text = text;
        }

        public string Id { get; }
        public string Path { get; }

        /// <summary>The full expanded text; the first line is <c>#line 1 "original path"</c>.</summary>
        public string Text { get; }
    }

    /// <summary>An extra file generated by the engine (e.g. the generated startup script).</summary>
    public sealed class GeneratedFile
    {
        public GeneratedFile(string name, string text)
        {
            Name = name;
            Text = text;
        }

        public string Name { get; }
        public string Text { get; }
    }

    public enum DiagnosticLevel { Warning, Error }

    public sealed class MacroDiagnostic
    {
        public MacroDiagnostic(DiagnosticLevel level, string code, string message, string filePath, int line, int column)
        {
            Level = level;
            Code = code;
            Message = message;
            FilePath = filePath;
            Line = line;
            Column = column;
        }

        public DiagnosticLevel Level { get; }
        public string Code { get; }
        public string Message { get; }
        public string FilePath { get; }
        public int Line { get; }
        public int Column { get; }

        /// <summary>Canonical MSBuild format, understood by IDEs and the Exec task.</summary>
        public override string ToString() =>
            $"{FilePath}({Line},{Column}): {(Level == DiagnosticLevel.Error ? "error" : "warning")} {Code}: {Message}";
    }

    /// <summary>Runtime information needed to locate a macro method (or an attribute macro's constructor).</summary>
    public sealed class MacroMethod
    {
        public const string Constructor = ".ctor";

        public MacroMethod(MetadataReference reference, string typeName, string methodName, int arity, int parameterCount)
        {
            Reference = reference;
            TypeName = typeName;
            MethodName = methodName;
            Arity = arity;
            ParameterCount = parameterCount;
        }

        /// <summary>
        /// Reference to the macro assembly. In command-line builds this is a DLL on disk (<see cref="PortableExecutableReference"/>);
        /// in the IDE a project reference is usually an in-memory compilation (<see cref="CompilationReference"/>) that the host must emit itself.
        /// </summary>
        public MetadataReference Reference { get; }

        /// <summary>Disk path of the reference; null for in-memory project references.</summary>
        public string? AssemblyPath => (Reference as PortableExecutableReference)?.FilePath;

        /// <summary>Type metadata name for reflection (nested types use +).</summary>
        public string TypeName { get; }

        /// <summary>Method name; <see cref="Constructor"/> for attribute macros.</summary>
        public string MethodName { get; }

        public int Arity { get; }
        public int ParameterCount { get; }
    }

    /// <summary>
    /// The host actually runs macros (loading assemblies, invoking via reflection).
    /// The engine itself stays netstandard2.0 and doesn't depend on platform APIs such as AssemblyLoadContext.
    /// </summary>
    public interface IMacroInvoker
    {
        /// <summary>Runs the macro in <paramref name="context"/>; exceptions from the macro body are thrown as is.</summary>
        void Invoke(MacroMethod method, MacroContext context);
    }

    public sealed class ExpandOptions
    {
        public IReadOnlyList<string> References { get; set; } = new string[0];
        public IReadOnlyList<string> Defines { get; set; } = new string[0];
        public string? LanguageVersion { get; set; }

        /// <summary>The project's Nullable setting (enable / disable / warnings / annotations); affects IsNullable in semantic information.</summary>
        public string? Nullable { get; set; }

        /// <summary>The project's output type (Exe / WinExe / Library). Top-level statements require Exe, otherwise the analysis compilation reports errors.</summary>
        public string? OutputType { get; set; }

        /// <summary>
        /// Attribute on the generated startup script's entry point. Regular .NET uses ModuleInitializer;
        /// hosts such as Unity can switch to <c>global::UnityEngine.RuntimeInitializeOnLoadMethod</c>.
        /// </summary>
        public string StartupAttribute { get; set; } = "global::System.Runtime.CompilerServices.ModuleInitializer";

        /// <summary>After expansion, compile-check the macro-generated code and report which macro generated any error.</summary>
        public bool Verify { get; set; } = true;

        /// <summary>
        /// Only expand these macros (names may be written LOGGED, @LOGGED, Save or [@Save]); null means all.
        /// For debugging: other macros stay as they are (they are valid method calls and attributes anyway).
        /// Note: attribute macros that aren't selected don't run, so method macros that depend on their fragments get fewer fragments.
        /// </summary>
        public IReadOnlyCollection<string>? Macros { get; set; }

        /// <summary>Runtime cleanup: remove unused usings that import macro libraries and report macro assemblies no longer needed at runtime (see <see cref="ExpandResult.RuntimeUnusedReferences"/>).</summary>
        public bool RuntimeCleanup { get; set; } = true;
    }

    /// <summary>Record of one macro expansion, for the expansion report and tests.</summary>
    public sealed class MacroExpansion
    {
        public MacroExpansion(string filePath, int line, string macro, string kind, string source, string output, string formatted)
        {
            FilePath = filePath;
            Line = line;
            Macro = macro;
            Kind = kind;
            Source = source;
            Output = output;
            Formatted = formatted;
        }

        public string FilePath { get; }
        public int Line { get; }

        /// <summary><c>@LOGGED</c> or <c>[@Save]</c>.</summary>
        public string Macro { get; }

        /// <summary>Method macros: Expression / Statement / Member; attribute macros: Fragment:channel / Startup.</summary>
        public string Kind { get; }

        /// <summary>The replaced source (method macros) or the attribute's source text (attribute macros).</summary>
        public string Source { get; }

        /// <summary>The one line of code actually written into the expanded file (method macros) or the produced fragment (attribute macros).</summary>
        public string Output { get; }

        /// <summary>The output formatted over multiple lines, for readability.</summary>
        public string Formatted { get; }
    }

    public sealed class ExpandResult
    {
        public ExpandResult(List<ExpandedFile> files, List<GeneratedFile> generatedFiles, List<MacroDiagnostic> diagnostics,
            IReadOnlyList<MacroExpansion>? expansions = null)
        {
            Expansions = expansions ?? new MacroExpansion[0];
            Files = files;
            GeneratedFiles = generatedFiles;
            Diagnostics = diagnostics;
        }

        /// <summary>Only files where something was expanded; files without macros are compiled as is.</summary>
        public List<ExpandedFile> Files { get; }

        /// <summary>Extra files generated by the engine that must be added to the compilation.</summary>
        public List<GeneratedFile> GeneratedFiles { get; }

        public List<MacroDiagnostic> Diagnostics { get; }

        /// <summary>Record of every macro expansion (sorted by file and line).</summary>
        public IReadOnlyList<MacroExpansion> Expansions { get; }

        /// <summary>Macro assemblies (disk paths) no longer needed at runtime after expansion. The host should remove them from compile references and output.</summary>
        public IReadOnlyList<string> RuntimeUnusedReferences { get; set; } = new string[0];

        /// <summary>
        /// Whether the runtime cleanup analysis is reliable. When the analysis compilation has errors (e.g. it depends on types produced by source generators),
        /// Roslyn counts every reference as used, so <see cref="RuntimeUnusedReferences"/> errs on the safe side (nothing is removed).
        /// </summary>
        public bool RuntimeAnalysisReliable { get; set; }

        public bool HasErrors => Diagnostics.Exists(d => d.Level == DiagnosticLevel.Error);
    }

    /// <summary>Result of <see cref="MacroExpander.ExpandTrees"/>.</summary>
    public sealed class ExpansionResult
    {
        public ExpansionResult(
            IReadOnlyList<SyntaxTree> expanded,
            Dictionary<SyntaxTree, Dictionary<int, string>> expansionLines,
            string? startupCode,
            IReadOnlyList<MacroFragment> startupFragments,
            IReadOnlyList<MacroExpansion> expansions)
        {
            Expansions = expansions;
            Expanded = expanded;
            ExpansionLines = expansionLines;
            StartupCode = startupCode;
            StartupFragments = startupFragments;
        }

        /// <summary>One per input; files without macros are the original tree itself.</summary>
        public IReadOnlyList<SyntaxTree> Expanded { get; }

        /// <summary>For each expanded tree, which lines were generated by macros (line number → macro name).</summary>
        public Dictionary<SyntaxTree, Dictionary<int, string>> ExpansionLines { get; }

        /// <summary>The generated startup script; null when there is no startup code.</summary>
        public string? StartupCode { get; }

        public IReadOnlyList<MacroFragment> StartupFragments { get; }

        public IReadOnlyList<MacroExpansion> Expansions { get; }
    }
}
